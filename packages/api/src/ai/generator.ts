/**
 * Generate images using OpenAI DALL-E 3 API
 */
async function generateWithOpenAI(
  config: AIProviderConfig,
  prompt: string,
  dimensions: { width: number; height: number },
  variationCount: number,
  baseSeed?: number
): Promise<GeneratedImage[]> {
  const images: GeneratedImage[] = [];

  // DALL-E 3 endpoint
  const endpoint = config.endpoint || "https://api.openai.com/v1/images/generations";

  // Map dimensions to DALL-E 3 supported sizes
  const size = mapToDalleSize(dimensions);

  // DALL-E 3 only generates 1 image per request
  for (let i = 0; i < variationCount; i++) {
    const seed = baseSeed !== undefined ? baseSeed + i : Math.floor(Math.random() * 2147483647);

    const response = await fetch(endpoint, {
      method: "POST",
      headers: {
        Authorization: `Bearer ${config.apiKey}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: config.modelId,
        prompt,
        n: 1,
        size,
        quality: "standard",
        response_format: "url",
      }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      throw new Error(`OpenAI API error: ${response.status} - ${errorText}`);
    }

    const result = (await response.json()) as {
      data: Array<{ url: string; revised_prompt?: string }>;
    };

    if (result.data && result.data.length > 0 && result.data[0]) {
      const imageUrl = result.data[0].url;
      const imageBuffer = await fetchImageAsBuffer(imageUrl);

      images.push({
        buffer: imageBuffer,
        url: imageUrl,
        width: dimensions.width,
        height: dimensions.height,
        seed, // DALL-E doesn't use seeds, but we track it for consistency
        variationIndex: i,
        mimeType: "image/png",
      });
    }
  }

  return images;
}

/**
 * Map dimensions to DALL-E 3 supported sizes
 */
function mapToDalleSize(dimensions: { width: number; height: number }): string {
  const { width, height } = dimensions;

  // DALL-E 3 supported sizes: 1024x1024, 1024x1792, 1792x1024
  if (width === height) {
    return "1024x1024";
  } else if (height > width) {
    return "1024x1792";
  } else {
    return "1792x1024";
  }
}

