/**
 * Check if a prompt contains banned content
 *
 * @param prompt - The prompt to check
 * @param bannedPatterns - Array of banned patterns (regex strings)
 * @returns Object indicating if content is safe and any matched patterns
 */
export function checkPromptModeration(
  prompt: string,
  bannedPatterns: Array<{ pattern: string; isRegex: boolean; category: string }>
): {
  isSafe: boolean;
  matchedPatterns: Array<{ pattern: string; category: string }>;
  riskScore: number;
} {
  const lowerPrompt = prompt.toLowerCase();
  const matchedPatterns: Array<{ pattern: string; category: string }> = [];

  for (const bannedPattern of bannedPatterns) {
    let isMatch = false;

    if (bannedPattern.isRegex) {
      try {
        const regex = new RegExp(bannedPattern.pattern, "i");
        isMatch = regex.test(prompt);
      } catch {
        // Invalid regex, skip
        continue;
      }
    } else {
      isMatch = lowerPrompt.includes(bannedPattern.pattern.toLowerCase());
    }

    if (isMatch) {
      matchedPatterns.push({
        pattern: bannedPattern.pattern,
        category: bannedPattern.category,
      });
    }
  }

  // Calculate risk score based on number and severity of matches
  const riskScore = Math.min(matchedPatterns.length * 0.25, 1.0);

  return {
    isSafe: matchedPatterns.length === 0,
    matchedPatterns,
    riskScore,
  };
}

