/**
 * Get provider configuration from environment
 */
function getProviderConfig(provider: AIModelProvider): AIProviderConfig | null {
  switch (provider) {
    case "stable-diffusion":
      const replicateKey = process.env.REPLICATE_API_TOKEN;
      if (!replicateKey) return null;
      return {
        apiKey: replicateKey,
        modelId: REPLICATE_MODELS.sdxl,
        timeout: 120000, // 2 minutes
      };

    case "dall-e-3":
      const openaiKey = process.env.OPENAI_API_KEY;
      if (!openaiKey) return null;
      return {
        apiKey: openaiKey,
        modelId: OPENAI_MODELS.dalleE3,
        timeout: 60000, // 1 minute
      };

    case "fal-ai":
      const falKey = process.env.FAL_API_KEY;
      if (!falKey) return null;
      return {
        apiKey: falKey,
        modelId: FAL_MODELS.fluxSchnell,
        timeout: 90000, // 1.5 minutes
      };

    default:
      return null;
  }
}

/**
 * Check if a provider is configured and available
 */
export function isProviderAvailable(provider: AIModelProvider): boolean {
  return getProviderConfig(provider) !== null;
}

/**
 * Get the first available provider
 */
export function getAvailableProvider(): AIModelProvider | null {
  const providers: AIModelProvider[] = ["stable-diffusion", "dall-e-3", "fal-ai"];
  for (const provider of providers) {
    if (isProviderAvailable(provider)) {
      return provider;
    }
  }
  return null;
}

