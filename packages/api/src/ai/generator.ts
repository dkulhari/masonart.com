// Replicate Provider (Stable Diffusion SDXL)
// ============================================================================

/**
 * Generate images using Replicate API (Stable Diffusion SDXL)
 */
async function generateWithReplicate(
  config: AIProviderConfig,
  prompt: string,
  negativePrompt: string,
  dimensions: { width: number; height: number },
  variationCount: number,
  baseSeed?: number
): Promise<GeneratedImage[]> {
  const images: GeneratedImage[] = [];

  // Replicate prediction API endpoint
  const endpoint = config.endpoint || "https://api.replicate.com/v1/predictions";

  for (let i = 0; i < variationCount; i++) {
    const seed = baseSeed !== undefined ? baseSeed + i : Math.floor(Math.random() * 2147483647);

    const response = await fetch(endpoint, {
      method: "POST",
      headers: {
        Authorization: `Token ${config.apiKey}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        version: config.modelId.split(":")[1],
        input: {
          prompt,
          negative_prompt: negativePrompt,
          width: dimensions.width,
          height: dimensions.height,
          seed,
          num_outputs: 1,
          guidance_scale: 7.5,
          num_inference_steps: 30,
          scheduler: "DPM++ 2M Karras",
        },
      }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      throw new Error(`Replicate API error: ${response.status} - ${errorText}`);
    }

    const prediction = (await response.json()) as {
      id: string;
      urls: { get: string };
      status: string;
    };

    // Poll for completion
    const result = await pollReplicatePrediction(config.apiKey, prediction.urls.get, config.timeout);

    if (result.status === "succeeded" && result.output && Array.isArray(result.output)) {
      const imageUrl = result.output[0] as string;
      const imageBuffer = await fetchImageAsBuffer(imageUrl);

      images.push({
        buffer: imageBuffer,
        url: imageUrl,
        width: dimensions.width,
        height: dimensions.height,
        seed,
        variationIndex: i,
        mimeType: "image/png",
      });
    } else if (result.status === "failed") {
      throw new Error(`Replicate prediction failed: ${result.error || "Unknown error"}`);
    }
  }

  return images;
}

/**
 * Poll Replicate prediction status until completion
 */
async function pollReplicatePrediction(
  apiKey: string,
  url: string,
  timeout: number
): Promise<{
  status: string;
  output?: unknown[];
  error?: string;
}> {
  const startTime = Date.now();
  const pollInterval = 1000; // 1 second

  while (Date.now() - startTime < timeout) {
    const response = await fetch(url, {
      headers: {
        Authorization: `Token ${apiKey}`,
      },
    });

    if (!response.ok) {
      throw new Error(`Failed to poll prediction: ${response.status}`);
    }

    const prediction = (await response.json()) as {
      status: string;
      output?: unknown[];
      error?: string;
    };

    if (prediction.status === "succeeded" || prediction.status === "failed") {
      return prediction;
    }

    // Wait before polling again
    await sleep(pollInterval);
  }

  throw new Error("Prediction timed out");
}

