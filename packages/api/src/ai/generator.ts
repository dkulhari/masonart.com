/**
 * Estimate generation cost in cents for a given configuration
 */
export function estimateGenerationCost(
  provider: AIModelProvider,
  variationCount: number
): number {
  // Approximate costs per image in cents
  const costPerImage: Record<AIModelProvider, number> = {
    "stable-diffusion": 2, // ~$0.02 per image on Replicate
    "dall-e-3": 8, // ~$0.08 per image (standard quality)
    midjourney: 10, // ~$0.10 per image (estimate)
    "fal-ai": 1, // ~$0.01 per image (FLUX Schnell)
  };

  return (costPerImage[provider] || 5) * variationCount;
}

/**
 * Get estimated generation time in seconds
 */
export function estimateGenerationTime(
  provider: AIModelProvider,
  variationCount: number
): number {
  // Approximate time per image in seconds
  const timePerImage: Record<AIModelProvider, number> = {
    "stable-diffusion": 15, // ~15s per image on Replicate SDXL
    "dall-e-3": 10, // ~10s per image on DALL-E 3
    midjourney: 30, // ~30s per image
    "fal-ai": 5, // ~5s per image (FLUX Schnell is fast)
  };

  // Add some overhead time for API calls
  const overhead = 5;

  return (timePerImage[provider] || 15) * variationCount + overhead;
}

/**
 * Get style preset configuration for display
 */
export function getStylePresetInfo(stylePreset: AIStylePreset): {
  name: string;
  description: string;
  keywords: string[];
  category: string;
  isPremium: boolean;
} | null {
  const preset = STYLE_PRESETS[stylePreset];
  if (!preset) return null;

  return {
    name: preset.name,
    description: preset.description,
    keywords: preset.keywords,
    category: preset.category,
    isPremium: preset.isPremium,
  };
}

/**
 * Validate generation input
 */
export function validateGenerationInput(input: AIGenerationInput): {
  isValid: boolean;
  errors: string[];
} {
  const errors: string[] = [];

  // Check prompt
  if (!input.prompt || input.prompt.trim().length === 0) {
    errors.push("Prompt is required");
  } else if (input.prompt.length > 2000) {
    errors.push("Prompt must be 2000 characters or less");
  }

  // Check style preset
  if (!STYLE_PRESETS[input.stylePreset]) {
    errors.push(`Invalid style preset: ${input.stylePreset}`);
  }

  // Check aspect ratio
  const validAspectRatios: AIAspectRatio[] = ["square", "portrait", "landscape", "panoramic"];
  if (!validAspectRatios.includes(input.aspectRatio)) {
    errors.push(`Invalid aspect ratio: ${input.aspectRatio}`);
  }

  // Check seed if provided
  if (input.seed !== undefined && (input.seed < 0 || input.seed > 2147483647)) {
    errors.push("Seed must be between 0 and 2147483647");
  }

  return {
    isValid: errors.length === 0,
    errors,
  };
}

