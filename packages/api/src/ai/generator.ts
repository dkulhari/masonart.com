/**
 * Generate AI images using the specified provider
 *
 * @param input - Generation input parameters
 * @param variationCount - Number of variations to generate (1-4)
 * @returns Generation result with images
 */
export async function generateImages(
  input: AIGenerationInput,
  variationCount: number = 4
): Promise<AIGenerationResult> {
  const startTime = Date.now();
  const provider = input.provider || getAvailableProvider() || "stable-diffusion";
  const config = getProviderConfig(provider);

  if (!config) {
    return {
      success: false,
      images: [],
      enhancedPrompt: input.prompt,
      negativePrompt: input.negativePrompt || "",
      provider,
      processingTimeMs: Date.now() - startTime,
      error: `AI provider ${provider} is not configured. Please set the appropriate API key.`,
    };
  }

  // Construct enhanced prompts
  const enhancedPrompt = constructEnhancedPrompt(input.prompt, input.stylePreset, {
    colorMood: input.colorMood,
    colorPalette: input.colorPalette,
  });

  const negativePrompt = constructNegativePrompt(
    input.stylePreset,
    input.negativePrompt
  );

  // Get dimensions for the provider
  const dimensions = getImageDimensions(input.aspectRatio, provider);

  try {
    let images: GeneratedImage[];

    switch (provider) {
      case "stable-diffusion":
        images = await generateWithReplicate(
          config,
          enhancedPrompt,
          negativePrompt,
          dimensions,
          variationCount,
          input.seed
        );
        break;

      case "dall-e-3":
        images = await generateWithOpenAI(
          config,
          enhancedPrompt,
          dimensions,
          variationCount,
          input.seed
        );
        break;

      case "fal-ai":
        images = await generateWithFalAI(
          config,
          enhancedPrompt,
          negativePrompt,
          dimensions,
          variationCount,
          input.seed
        );
        break;

      default:
        throw new Error(`Unsupported provider: ${provider}`);
    }

    return {
      success: true,
      images,
      enhancedPrompt,
      negativePrompt,
      provider,
      modelVersion: config.modelId,
      processingTimeMs: Date.now() - startTime,
    };
  } catch (error) {
    const errorMessage = error instanceof Error ? error.message : "Unknown error occurred";
    return {
      success: false,
      images: [],
      enhancedPrompt,
      negativePrompt,
      provider,
      modelVersion: config.modelId,
      processingTimeMs: Date.now() - startTime,
      error: errorMessage,
    };
  }
}

