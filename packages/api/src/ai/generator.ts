/**
 * Input for AI image generation
 */
export interface AIGenerationInput {
  /** User's text prompt */
  prompt: string;
  /** Optional negative prompt */
  negativePrompt?: string;
  /** Style preset to apply */
  stylePreset: AIStylePreset;
  /** Aspect ratio for the output */
  aspectRatio: AIAspectRatio;
  /** Optional color mood */
  colorMood?: string;
  /** Optional specific color palette */
  colorPalette?: string[];
  /** Seed for reproducibility (optional) */
  seed?: number;
  /** AI model provider to use */
  provider?: AIModelProvider;
}

/**
 * Generated image result
 */
export interface GeneratedImage {
  /** Image data as Buffer */
  buffer: Buffer;
  /** Image URL (if generated by provider) */
  url?: string;
  /** Width in pixels */
  width: number;
  /** Height in pixels */
  height: number;
  /** Seed used for generation */
  seed: number;
  /** Variation index (0-based) */
  variationIndex: number;
  /** MIME type */
  mimeType: string;
}

/**
 * Generation result from AI provider
 */
export interface AIGenerationResult {
  /** Whether generation was successful */
  success: boolean;
  /** Generated images */
  images: GeneratedImage[];
  /** Enhanced prompt that was used */
  enhancedPrompt: string;
  /** Negative prompt that was used */
  negativePrompt: string;
  /** Model provider used */
  provider: AIModelProvider;
  /** Model version/identifier */
  modelVersion?: string;
  /** Processing time in milliseconds */
  processingTimeMs: number;
  /** Error message if failed */
  error?: string;
  /** Cost in cents (if available) */
  costCents?: number;
}

/**
 * Provider-specific configuration
 */
export interface AIProviderConfig {
  /** API key */
  apiKey: string;
  /** API endpoint (for custom endpoints) */
  endpoint?: string;
  /** Model identifier */
  modelId: string;
  /** Timeout in milliseconds */
  timeout: number;
}

