/**
 * Generate images using FAL.ai API
 */
async function generateWithFalAI(
  config: AIProviderConfig,
  prompt: string,
  negativePrompt: string,
  dimensions: { width: number; height: number },
  variationCount: number,
  baseSeed?: number
): Promise<GeneratedImage[]> {
  const images: GeneratedImage[] = [];

  // FAL.ai endpoint
  const endpoint = `https://fal.run/${config.modelId}`;

  for (let i = 0; i < variationCount; i++) {
    const seed = baseSeed !== undefined ? baseSeed + i : Math.floor(Math.random() * 2147483647);

    const response = await fetch(endpoint, {
      method: "POST",
      headers: {
        Authorization: `Key ${config.apiKey}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        prompt,
        negative_prompt: negativePrompt,
        image_size: {
          width: dimensions.width,
          height: dimensions.height,
        },
        seed,
        num_images: 1,
        sync_mode: true,
      }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      throw new Error(`FAL.ai API error: ${response.status} - ${errorText}`);
    }

    const result = (await response.json()) as {
      images: Array<{ url: string; width: number; height: number }>;
    };

    if (result.images && result.images.length > 0 && result.images[0]) {
      const imageData = result.images[0];
      const imageBuffer = await fetchImageAsBuffer(imageData.url);

      images.push({
        buffer: imageBuffer,
        url: imageData.url,
        width: imageData.width ?? dimensions.width,
        height: imageData.height ?? dimensions.height,
        seed,
        variationIndex: i,
        mimeType: "image/png",
      });
    }
  }

  return images;
}

